#!/usr/bin/env python3
# Embed the Adreno 630 CP microcode (a630_sqe.fw) and the OnePlus-signed zap
# shader (a630_zap.mbn) into the C headers the OP6 shim stage m13 includes
# (op6/shim/m13.c). Both are Qualcomm proprietary and NEVER committed: this
# writes op6/shim/fw_a630_sqe.h and op6/shim/fw_a630_zap.h, both git-ignored.
# Companion of gpu-fw-embed.py (GMU firmware, m10..m13).
#
# The files are embedded whole, as 32-bit little-endian words; m13 parses the
# zap ELF itself on the phone. The checks here only refuse obviously wrong
# files before a build.
#
#   op6/tools/gpu-fw-embed-cp.py ../gpu-fw/a630_sqe.fw ../gpu-fw/a630_zap.mbn
#   op6/tools/gpu-fw-embed-cp.py --remove
import hashlib
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SHIM = os.path.join(HERE, "..", "shim")
OUT_SQE = os.path.join(SHIM, "fw_a630_sqe.h")
OUT_ZAP = os.path.join(SHIM, "fw_a630_zap.h")
# op6/GPU-NOTES.md sec. 4 (checked 2026-11-10)
SQE_SHA256 = "1c21b527d9183487cc550dabbb3f43e555df5a977a461934fc61f0635a9aa90c"
ZAP_SHA256 = "9780956733759d24740b3df5bd804e5dddc48bc0e956271b0288631890080df9"
ZAP_REGION = 0x2000		# DT gpu@8c415000 reserved size


def words_of(data):
    return [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]


def write_header(path, what, src, data, guard, name):
    sha = hashlib.sha256(data).hexdigest()
    w = words_of(data)
    with open(path, "w") as f:
        f.write("/* GENERATED by op6/tools/gpu-fw-embed-cp.py from %s (Qualcomm; NOT in git).\n" % what)
        f.write(" * %d bytes, sha256 %s */\n" % (len(data), sha))
        f.write("#define %s 1\n" % guard)
        f.write("#define %s_BYTES %du\n" % (name.upper(), len(data)))
        f.write("static const uint32_t %s[%d] = {\n" % (name, len(w)))
        for i in range(0, len(w), 8):
            f.write("\t" + " ".join("0x%08xu," % x for x in w[i:i + 8]) + "\n")
        f.write("};\n")
    print("wrote %s (%d words, sha256 %s)" % (path, len(w), sha[:16]))


def check_sqe(data):
    if len(data) % 4 or not (0x1000 <= len(data) <= 0x40000):
        return "unexpected size %d" % len(data)
    ver = struct.unpack_from("<I", data, 4)[0]	# Linux: buf[0] of the BO = file word 1
    patched = (ver & 0xf) == 0xa and (struct.unpack_from("<I", data, 12)[0] & 0xf) >= 1
    if not patched and (ver & 0xfff) < 0x190:
        return "SQE version %x < 0x190 (Linux a6xx_ucode_check_version refuses it)" % (ver & 0xfff)
    return None


def check_zap(data):
    if data[:4] != b"\x7fELF" or data[4] != 1 or data[5] != 1:
        return "not a little-endian ELF32"
    if len(data) % 4:
        return "size not a multiple of 4"
    phoff, = struct.unpack_from("<I", data, 28)
    phentsize, phnum = struct.unpack_from("<HH", data, 42)
    if phoff != 52 or phentsize != 32 or not (2 <= phnum <= 16):
        return "odd program headers (off %d, size %d, n %d)" % (phoff, phentsize, phnum)
    ph = [struct.unpack_from("<8I", data, phoff + 32 * i) for i in range(phnum)]
    if ph[0][0] == 1:
        return "first phdr is PT_LOAD (not an MDT image)"
    hashes = [i for i in range(1, phnum) if (ph[i][6] & (7 << 24)) == (2 << 24)]
    if not hashes:
        return "no hash segment"
    lo, hi = None, 0
    for t, off, va, pa, fsz, msz, fl, al in ph:
        if t != 1 or (fl & (7 << 24)) == (2 << 24) or not msz:
            continue
        if off + fsz > len(data):
            return "segment beyond the file (split image)"
        lo = pa if lo is None else min(lo, pa)
        hi = max(hi, (pa + msz + 0xfff) & ~0xfff)
    if lo is None or hi - lo > ZAP_REGION:
        return "load size %#x does not fit the %#x carve-out" % (hi - (lo or 0), ZAP_REGION)
    return None


def main():
    if len(sys.argv) == 2 and sys.argv[1] == "--remove":
        for p in (OUT_SQE, OUT_ZAP):
            if os.path.exists(p):
                os.remove(p)
                print("removed %s" % p)
        return 0
    if len(sys.argv) != 3:
        print("usage: gpu-fw-embed-cp.py a630_sqe.fw a630_zap.mbn | --remove", file=sys.stderr)
        return 2
    sqe = open(sys.argv[1], "rb").read()
    zap = open(sys.argv[2], "rb").read()
    for what, data, check, known in (("a630_sqe.fw", sqe, check_sqe, SQE_SHA256),
                                     ("a630_zap.mbn", zap, check_zap, ZAP_SHA256)):
        err = check(data)
        if err:
            print("%s: %s" % (what, err), file=sys.stderr)
            return 2
        if hashlib.sha256(data).hexdigest() != known:
            print("warning: %s sha256 differs from GPU-NOTES.md (%s...)" % (what, known[:16]), file=sys.stderr)
    write_header(OUT_SQE, "a630_sqe.fw", sys.argv[1], sqe, "HAVE_SQE_FW", "a630_sqe_fw")
    write_header(OUT_ZAP, "a630_zap.mbn", sys.argv[2], zap, "HAVE_ZAP_FW", "a630_zap_fw")
    return 0


if __name__ == "__main__":
    sys.exit(main())
