#!/usr/bin/env python3
# Embed the Adreno 630 GMU firmware (a630_gmu.bin) into the C header the OP6
# shim stages m10/m11 include (op6/shim/gpu.c). The firmware is Qualcomm
# proprietary (redistributable under linux-firmware LICENSE.qcom) and NEVER
# committed: this writes op6/shim/fw_a630_gmu.h, which is git-ignored.
# Derived from s9/tools/gpu-fw-embed.py.
#
# a630 = "legacy" GMU: the file is a raw ITCM image written one 32-bit word at
# a time through the AHB window (Linux a6xx_gmu_fw_load, legacy: <= 0x8000
# bytes). The linux-firmware qcom/a630_gmu.bin is 32768 bytes = 8192 words.
#
#   op6/tools/gpu-fw-embed.py ../gpu-fw/a630_gmu.bin     then: bash op6/build.sh m10
#   op6/tools/gpu-fw-embed.py --remove                   back to "no firmware" builds
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "shim", "fw_a630_gmu.h")
# linux-firmware qcom/a630_gmu.bin as checked in the S9 study (2026-10-25)
KNOWN_SHA256 = "da8d9b1b1f5c1a0b311f32567093b4828f3c80031dd8435f91ac13c664e173a6"


def main():
    if len(sys.argv) == 2 and sys.argv[1] == "--remove":
        if os.path.exists(OUT):
            os.remove(OUT)
            print("removed %s" % OUT)
        return 0
    if len(sys.argv) != 2:
        print("usage: gpu-fw-embed.py path/to/a630_gmu.bin | --remove", file=sys.stderr)
        return 2
    data = open(sys.argv[1], "rb").read()
    if len(data) % 4:
        print("not a whole number of 32-bit words: %d bytes" % len(data), file=sys.stderr)
        return 2
    if not (0x4000 <= len(data) <= 0x8000):
        print("unexpected size %d (a630_gmu.bin is 32768 bytes; legacy limit 0x8000)" % len(data),
              file=sys.stderr)
        return 2
    sha = hashlib.sha256(data).hexdigest()
    if sha != KNOWN_SHA256:
        print("warning: sha256 %s differs from the linux-firmware file the S9 booted (%s)"
              % (sha, KNOWN_SHA256[:16]), file=sys.stderr)
    words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
    with open(OUT, "w") as f:
        f.write("/* GENERATED by op6/tools/gpu-fw-embed.py from a630_gmu.bin (Qualcomm; NOT in git).\n")
        f.write(" * %d bytes, sha256 %s */\n" % (len(data), sha))
        f.write("#define HAVE_GMU_FW 1\n")
        f.write("static const uint32_t a630_gmu_fw[%d] = {\n" % len(words))
        for i in range(0, len(words), 8):
            f.write("\t" + " ".join("0x%08xu," % w for w in words[i:i + 8]) + "\n")
        f.write("};\n")
    print("wrote %s (%d words, sha256 %s)" % (OUT, len(words), sha[:16]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
